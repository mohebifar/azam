// Generates crates/azam-io/src/pdf/metrics_data.rs: advance widths and kerning pairs of the PDF
// base-14 Helvetica faces, as used by jsPDF 2.5.1 (the library src.js draws its PDFs with), so the
// Rust pattern PDF measures text exactly as the reference does.
//
//   (cd tools/golden && npm install)
//   node tools/golden/gen-font-metrics.mjs > crates/azam-io/src/pdf/metrics_data.rs
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { jsPDF } = require('jspdf');

const pdf = new jsPDF({ unit: 'mm', format: 'a4' });
const faces = [['normal', 'REGULAR'], ['bold', 'BOLD'], ['italic', 'OBLIQUE']];
const lines = [
  '//! Advance widths and kerning pairs of the base-14 Helvetica faces.',
  '//!',
  '//! Generated by `tools/golden/gen-font-metrics.mjs`; do not edit.',
  '',
  'use super::metrics::FaceMetrics;',
  '',
];
for (const [style, name] of faces) {
  pdf.setFont('helvetica', style);
  const f = pdf.internal.getFont();
  const w = f.metadata.Unicode.widths;
  const k = f.metadata.Unicode.kerning;
  const widths = Object.keys(w).filter((c) => c !== 'fof').map(Number).sort((a, b) => a - b);
  const pairs = [];
  for (const c of Object.keys(k).filter((c) => c !== 'fof').map(Number)) {
    for (const p of Object.keys(k[c]).map(Number)) pairs.push([c, p, k[c][p]]);
  }
  pairs.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  lines.push(`/// ${f.postScriptName}.`);
  lines.push(`pub(super) const ${name}: FaceMetrics = FaceMetrics {`);
  lines.push(`    width_unit: ${w.fof}.0,`);
  lines.push(`    kerning_unit: ${k.fof}.0,`);
  lines.push('    widths: &[');
  for (let i = 0; i < widths.length; i += 8) {
    lines.push(`        ${widths.slice(i, i + 8).map((c) => `(${c}, ${w[c]})`).join(', ')},`);
  }
  lines.push('    ],');
  lines.push('    kerning: &[');
  for (let i = 0; i < pairs.length; i += 6) {
    lines.push(`        ${pairs.slice(i, i + 6).map(([c, p, v]) => `(${c}, ${p}, ${v})`).join(', ')},`);
  }
  lines.push('    ],');
  lines.push('};');
  lines.push('');
}
process.stdout.write(lines.join('\n'));
